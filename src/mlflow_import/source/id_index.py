"""Bounded private ID sets used by source discovery, never transcript storage."""

from __future__ import annotations

import hashlib
import os
import sqlite3
from collections.abc import Iterable, Iterator, MutableSet

from mlflow_import import resources


class DiskIds(MutableSet[str]):
    """Set-compatible indexed IDs with an attachable SQL selection predicate."""

    def __init__(self, values: Iterable[str] = ()) -> None:
        self.root = resources.make_temp_dir(prefix="mlflow-import-ids-")
        self.path = self.root / "ids.db"
        self.db = resources.sqlite_connect(self.path, isolation_level=None)
        self._closed = False
        os.chmod(self.path, 0o600)
        self.db.executescript("""PRAGMA journal_mode=OFF; PRAGMA cache_size=-512;
            PRAGMA temp_store=FILE; PRAGMA max_page_count=262144;
            CREATE TABLE ids(id TEXT PRIMARY KEY);""")
        for value in values:
            self.add(value)

    def __contains__(self, value: object) -> bool:
        return (
            isinstance(value, str) and self.db.execute("SELECT 1 FROM ids WHERE id=?", (value,)).fetchone() is not None
        )

    def __len__(self) -> int:
        return int(self.db.execute("SELECT count(*) FROM ids").fetchone()[0])

    def __iter__(self) -> Iterator[str]:
        for (value,) in self.db.execute("SELECT id FROM ids ORDER BY id"):
            yield value

    def add(self, value: str) -> None:
        self.db.execute("INSERT OR IGNORE INTO ids VALUES(?)", (value,))

    def discard(self, value: str) -> None:
        self.db.execute("DELETE FROM ids WHERE id=?", (value,))

    def clear(self) -> None:
        self.db.execute("DELETE FROM ids")

    def predicate(self, connection: sqlite3.Connection, expression: str) -> tuple[str, tuple[str, ...]]:
        # Alias is generated by us, never source data. Both stores remain
        # independently read-only through the live connection's query_only.
        budget = resources.current_storage()
        if budget and getattr(connection, "budget", None) is not budget:
            from mlflow_import.errors import ConfigurationError

            raise ConfigurationError(
                "temporary_sql_unsupported", "temporary selections require an accounted parent connection"
            )
        alias = "selected_" + hashlib.sha256(str(self.path).encode()).hexdigest()
        if not any(row[1] == alias for row in connection.execute("PRAGMA database_list")):
            path = self.path.as_uri() + "?mode=ro" if resources.current_storage() else str(self.path)
            connection.execute(f'ATTACH DATABASE ? AS "{alias}"', (path,))
        return f' WHERE {expression} IN (SELECT id FROM "{alias}".ids)', ()

    def close(self) -> None:
        if not getattr(self, "_closed", True):
            self._closed = True
            budget = getattr(self.db, "budget", None)
            self.db.close()
            resources.remove_tree(self.root, owner=budget)

    def __del__(self) -> None:
        try:
            self.close()
        except (OSError, sqlite3.Error):
            pass
